import { rateLimit } from 'express-rate-limit';

const isTestEnv = ['test', 'pipeline'].includes(process.env.NODE_ENV);

// Per-IP limit for routes that read or write the database. `trust proxy` is set in server.ts.
export const apiRateLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  limit: 1000,
  standardHeaders: 'draft-7',
  legacyHeaders: false,
  skip: () => isTestEnv,
});

export default apiRateLimiter;
